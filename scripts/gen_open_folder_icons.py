"""Usage: python3 -I scripts/gen_open_folder_icons.py <material-icon-theme package dir> <kodact-desktop repo>

Copy the open variant of every folder icon in assets/file-icons (folder-src.svg ->
folder-src-open.svg) from the Material Icon Theme package (MIT, the same icons
the VS Code extension uses), and write src/ui/file_icon_open.rs listing them, so
the Files tab's explorer shows an open folder as VS Code does."""
import os, shutil, sys
pkg, gpui = sys.argv[1], sys.argv[2]
src = os.path.join(pkg, 'icons')
dst = os.path.join(gpui, 'assets/file-icons')
folders = sorted(f[:-4] for f in os.listdir(dst) if f.startswith('folder') and f.endswith('.svg') and not f.endswith('-open.svg'))
got = []
for name in folders:
    s = os.path.join(src, name + '-open.svg')
    if os.path.isfile(s):
        shutil.copy(s, os.path.join(dst, name + '-open.svg'))
        got.append(name + '-open')
with open(os.path.join(gpui, 'src/ui/file_icon_open.rs'), 'w') as f:
    f.write('//! Generated by scripts/gen_open_folder_icons.py: the open variant of each\n'
            '//! folder icon (Material Icon Theme, MIT; assets/file-icons/LICENSE). Do not edit.\n\n')
    f.write('/// Open folders\' icons, by asset path.\npub static OPEN_SVGS: &[(&str, &[u8])] = &[\n')
    for u in got:
        f.write(f'    ("file-icons/{u}.svg", include_bytes!("../../assets/file-icons/{u}.svg")),\n')
    f.write('];\n')
print(len(folders), len(got))
