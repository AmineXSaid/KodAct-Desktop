"""Usage: python3 -I scripts/gen_file_icons.py <FORGE repo> <forge-gpui repo>

Port the VS Code extension's file/folder icon maps and their SVGs to forge-gpui."""
import re, os, shutil, sys
forge, gpui = sys.argv[1], sys.argv[2]
icons = os.path.join(forge, 'assets/icons')
have = {f[:-4] for f in os.listdir(icons) if f.endswith('.svg')}

def resolve(name):  # Icon.vue resolveLocalId
    c = [name]
    if name.startswith('language-'): c.append(name[9:])
    if name.startswith('file-'): c.append(re.sub(r'-box$', '', name[5:]))
    if name.startswith('folder-'): c.append(name[7:])
    if name == 'microsoft-visual-studio-code': c.append('vscode')
    for x in c:
        if x in have: return x
    return None

entry = re.compile(r"^\s*'?([^':]+?)'?\s*:\s*\{\s*type:\s*'mdi',\s*icon:\s*'([^']+)'")
def parse(path, start, stop=None):
    out, on = {}, False
    for line in open(path, encoding='utf8'):
        if start in line: on = True; continue
        if on and stop and stop in line: break
        if on:
            m = entry.match(line)
            if m:
                r = resolve(m.group(2))
                if r: out[m.group(1)] = r  # a repeated key: the last wins, as in JS
            elif line.startswith('}'): on = False
    return out

cfg = os.path.join(forge, 'src/webview/src/config')
ext = parse(f'{cfg}/fileIconMap.ts', 'export const fileExtensionMap')
names = parse(f'{cfg}/fileIconMap.ts', 'export const specialFileNameMap')
folders = parse(f'{cfg}/folderIconMap.ts', 'export const folderNameMap')
used = sorted(set(ext.values()) | set(names.values()) | set(folders.values()) | {'file', 'folder', 'folder-gh-workflows' if 'folder-gh-workflows' in have else 'folder'})
dst = os.path.join(gpui, 'assets/file-icons'); os.makedirs(dst, exist_ok=True)
for u in used: shutil.copy(os.path.join(icons, u + '.svg'), dst)

def table(name, m):
    rows = ''.join(f'    ({k!r}, {v!r}),\n'.replace("'", '"') for k, v in sorted(m.items()))
    return f'pub static {name}: &[(&str, &str)] = &[\n{rows}];\n'
with open(os.path.join(gpui, 'src/ui/file_icon_map.rs'), 'w') as f:
    f.write('//! Generated by scripts/gen_file_icons.py from the VS Code extension\'s\n'
            '//! fileIconMap.ts and folderIconMap.ts (Material Icon Theme, MIT;\n'
            '//! assets/file-icons/LICENSE). Each table is sorted by key. Do not edit.\n\n')
    f.write('/// File names (and compound suffixes) to icons.\n' + table('NAMES', names) + '\n')
    f.write('/// Extensions, and compound suffixes like `spec.ts`, to icons.\n' + table('EXTENSIONS', ext) + '\n')
    f.write('/// Folder names (without a leading dot) to icons.\n' + table('FOLDERS', folders) + '\n')
    f.write('/// The icons, by asset path.\npub static SVGS: &[(&str, &[u8])] = &[\n')
    for u in used:
        f.write(f'    ("file-icons/{u}.svg", include_bytes!("../../assets/file-icons/{u}.svg")),\n')
    f.write('];\n')
print(len(ext), len(names), len(folders), len(used))
